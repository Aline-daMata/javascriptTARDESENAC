// OPERADORES COMPARAÇÃO - BOOLEAN: TRUE/FALSE
const num1 = 1;
const num2 = 5;
console.log(num1 < num2);
console.log(num1 > num2);

const num3 = 18;
const num4 = 18;
console.log(num3 <= num4);
console.log(num3 >= num4);

//escreva sempre ==, = não funciona
// === significa que irá comparar o valor e o tipo dele!

const a = 1;
const b = 1;
console.log(a === b); 

const c = 1;
const d = "a";
console.log(c == d); 

//comparação por diferenciação
// "!==": estritamente diferente; "!=": diferente.
const e = 1;
const f = 2;
console.log(e !== f); 

const g = 1;
const h = "1";
console.log(g != h); 